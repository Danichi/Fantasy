import type { NodeEffect } from '../paths/effects';

// What every node of the crafting Callings does (Smithing, Cooking, Tailoring,
// Runecraft). These used to fall back to a random "+8% quality" or a yield
// bonus nothing read; now each one names what it changes, and the crafting
// rules (crafter.ts) read the keys:
//   qWeapon qLight qHeavy qArmor qLightArmor qHeavyArmor qShield qRanged
//   qMeal qLeather qCloth qPack qAll  quality steps (1 = a whole step)
//   window   the timing mark is wider (fraction)
//   save     chance each unit of material isn't used up
//   twice    chance to make two
//   smelt    chance of an extra ingot when smelting
//   tan      chance of an extra hide, cloth or leather when refining at the loom
//   arrows   chance of a double bundle of arrows or bolts
//   salvage  more back from salvage (1 = everything)
//   practice faster practice in this Calling; practiceAll in every Calling
//   sharpen sharpTime patch  the Sharpen and Patch Armour techniques
//   temperCap temperCheap temperSafe  tempering (raising the quality of gear you own)
//   mealPower mealTime mealHeal  meals you eat are stronger, last longer, heal more
//   meat hide  more from a hunt's skinning
//   runeEdge runeWard runeKeep  runes you cut are stronger; overwriting gives the old rune back
//   yield gather rare  gathering (ore veins and timber)
// Active nodes ('*') of a Calling are recipes or station techniques.

